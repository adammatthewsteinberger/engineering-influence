MINIMAL: dict[str, Any] = {
    "title": "My Book",
    "author": "Ann Author",
    "publisher": "Pub House",
    "edition": "First Edition",
    "author_bio": "Ann writes.\n\nAnd more.",
}
FULL: dict[str, Any] = {
    **MINIMAL,
    "subtitle": "A Subtitle",
    "isbn": "978-1",
    "ebook_isbn": "978-2",
    "website": "https://pub.example",
    "email": "a@pub.example",
    "also_by": ["Earlier Book", "Another"],
    "dedication": "For you.",
    "copyright_notes": "Some notes.",
    "year": 2030,
    "number_chapters": False,
}


def chapters(kind: str) -> list[Chapter]:
    return [Chapter(Path("x.md"), kind, title=f"{kind} title", short="s", body="Body text.\n")]


def book(meta: dict[str, Any], with_back: bool = True) -> Book:
    return Book(
        "demo",
        meta,
        front=chapters("front"),
        parts=[("Part One", chapters("chapter"))],
        back=chapters("back") if with_back else [],
    )


def test_print_document_minimal_metadata() -> None:
    tex = PrintDocument().render(book(MINIMAL, with_back=False))
    assert tex.startswith("% Generated by engineering-influence from demo.toml. Do not edit.\n")
    assert (
        "\\documentclass{fine-book}" in tex
        and "\\setpdfinfo{My Book: }{Ann Author}{First Edition}" in tex
    )
    assert "ISBN" not in tex and "also by" not in tex and "\\backmatter" not in tex
    assert "Copyright \\copyright\\ 2026 Pub House." in tex
    assert "Ann writes.\n\nAnd more." in tex and "\\part{Part One}" in tex


def test_print_document_full_metadata_and_hardcover() -> None:
    tex = PrintDocument().render(book(FULL), hardcover=True)
    assert "\\documentclass{fine-book-hardcover}" in tex
    assert "ISBN 978-1\\\\\n" in tex and "\\url{https://pub.example}" in tex
    assert "\\href{mailto:a@pub.example}{a@pub.example}" in tex
    assert (
        "\\spacedcaps{also by ann author}" in tex
        and "\\emph{Earlier Book}\\\\[3pt]\n\\emph{Another}" in tex
    )
    assert "\\backmatter\n\\pagestyle{fine}\n" in tex and "For you." in tex
    assert "\\chapter*{chapter title}" in tex and "Copyright \\copyright\\ 2030" in tex


def test_ebook_document_minimal_metadata() -> None:
    tex = EbookDocument().render(book(MINIMAL, with_back=False))
    assert "\\usepackage{fine-ebook}" in tex and "ebookdedication" not in tex
    assert "\\emph{My Book}\\par" in tex and "(ebook)" not in tex
    assert "Published by Pub House\\par" in tex and "Also by" not in tex


def test_ebook_document_full_metadata() -> None:
    tex = EbookDocument().render(book(FULL))
    assert "\\emph{My Book: A Subtitle}\\par" in tex and "\\textit{A Subtitle}\\par" in tex
    assert "ISBN 978-2 (ebook)\\par" in tex
    assert (
        "\\url{https://pub.example}" in tex and "\\href{mailto:a@pub.example}{a@pub.example}" in tex
    )
    assert "\\begin{ebookdedication}\nFor you.\n\\end{ebookdedication}" in tex
    assert "\\section*{Also by Ann Author}\n\\emph{Earlier Book}\n\n\\emph{Another}" in tex


