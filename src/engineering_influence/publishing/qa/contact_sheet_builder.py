"""Contact sheets: labelled thumbnails of the rendered pages, sixteen to a sheet."""

from pathlib import Path

from PIL import Image, ImageDraw

from engineering_influence.publishing.covers.font_loader import FontLoader
from engineering_influence.publishing.package_assets import PackageAssets
from engineering_influence.publishing.path_relativizer import PathRelativizer
from engineering_influence.publishing.qa.page_file_number import PageFileNumber


class ContactSheetBuilder:
    """Page labels use the bundled DejaVu Serif, so sheets look the same on every machine."""

    def __init__(self, relativizer: PathRelativizer) -> None:
        self._relativizer = relativizer

    def clear(self, directory: Path) -> None:
        """Remove only contact sheets generated by an earlier run."""
        if not directory.exists():
            return
        for path in directory.glob("contact-*.png"):
            path.unlink()

    def build(self, page_paths: list[Path], output: Path, *, per_sheet: int = 16) -> list[str]:
        """Write contact-001.png ... into output; return their paths."""
        sheets: list[str] = []
        if not page_paths:
            return sheets
        with Image.open(page_paths[0]) as first:
            source_w, source_h = first.size
        thumb_w = 180
        thumb_h = max(1, round(source_h * thumb_w / source_w))
        columns = 4
        rows = (per_sheet + columns - 1) // columns
        label_h, margin = 26, 12
        sheet_w = columns * (thumb_w + margin) + margin
        sheet_h = rows * (thumb_h + label_h + margin) + margin
        numbers = PageFileNumber()
        with PackageAssets().directory() as assets:
            font = FontLoader([assets / "fonts"]).load("DejaVuSerif.ttf", 16)
        for start in range(0, len(page_paths), per_sheet):
            sheet = Image.new("RGB", (sheet_w, sheet_h), "white")
            draw = ImageDraw.Draw(sheet)
            for offset, page_path in enumerate(page_paths[start : start + per_sheet]):
                x = margin + (offset % columns) * (thumb_w + margin)
                y = margin + (offset // columns) * (thumb_h + label_h + margin)
                with Image.open(page_path) as image:
                    thumb = image.convert("RGB")
                    thumb.thumbnail((thumb_w, thumb_h), Image.Resampling.LANCZOS)
                    sheet.paste(thumb, (x + (thumb_w - thumb.width) // 2, y + label_h))
                draw.rectangle(
                    (x, y + label_h, x + thumb_w, y + label_h + thumb_h), outline=(150, 150, 150)
                )
                draw.text((x, y), f"Page {numbers.of(page_path)}", fill=(20, 20, 20), font=font)
            path = output / f"contact-{start // per_sheet + 1:03d}.png"
            sheet.save(path, format="PNG", optimize=True)
            sheets.append(self._relativizer.relative(path))
        return sheets
