"""The ebook's unique identifier and the metadata TeX hands to tex4ebook."""

import re
import uuid

from engineering_influence.publishing.typesetting.book import Book
from engineering_influence.publishing.typesetting.manuscript_error import ManuscriptError


class EpubIdentifier:
    """An ISBN-based identifier when the book has one, otherwise a stable UUID.

    The UUID is derived from the website, slug, and edition, so rebuilding never changes it.
    """

    DEFAULT_WEBSITE = "https://github.com/adammatthewsteinberger/engineering-influence"

    def __init__(self, default_website: str = DEFAULT_WEBSITE) -> None:
        self._default_website = default_website

    def of(self, book: Book) -> tuple[str, str]:
        """Return (identifier, kind) where kind is "ISBN" or "UUID"."""
        meta = book.meta
        if meta.get("ebook_isbn"):
            return "urn:isbn:" + re.sub(r"[^0-9Xx]", "", meta["ebook_isbn"]), "ISBN"
        seed = f"{meta.get('website', self._default_website)}/{book.slug}/{meta['edition']}"
        return "urn:uuid:" + str(uuid.uuid5(uuid.NAMESPACE_URL, seed)), "UUID"

    def meta_tex(self, book: Book) -> str:
        """Definitions read by fine-ebook.cfg. Only plain ASCII-safe values go here."""
        uid, _ = self.of(book)
        title = " ".join(book.meta["title"].split())
        if re.search(r'[&<>"#%\\{}~^$_]', title):
            raise ManuscriptError(f"title {title!r} has a character the ebook <title> cannot carry")
        return (
            "% Generated by engineering-influence. Do not edit.\n"
            f"\\def\\EbookIdentifier{{{uid}}}\n\\def\\EbookTitle{{{title}}}\n"
        )
