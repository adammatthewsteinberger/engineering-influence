"""The print-interior LaTeX document for the fine-book classes."""

from engineering_influence.publishing.typesetting.book import Book
from engineering_influence.publishing.typesetting.chapter_tex import ChapterTex
from engineering_influence.publishing.typesetting.tex_text import TexText


class PrintDocument:
    """Half title, title page, copyright, dedication, contents, chapters, and author note."""

    def __init__(self) -> None:
        self._tex = TexText()
        self._chapters = ChapterTex()

    def render(self, book: Book, hardcover: bool = False) -> str:
        """Return the complete .tex source."""
        m = book.meta
        tex_text = self._tex.text
        title = tex_text(m["title"])
        subtitle = tex_text(m.get("subtitle", ""))
        author = tex_text(m["author"])
        publisher = tex_text(m["publisher"])
        year = m.get("year", 2026)
        isbn_line = f"ISBN {tex_text(m['isbn'])}\\\\\n" if m.get("isbn") else ""
        contact = []
        if m.get("website"):
            contact.append(r"\url{" + m["website"] + "}")
        if m.get("email"):
            contact.append(r"\href{mailto:" + m["email"] + "}{" + m["email"] + "}")
        contact_tex = "\\\\\n".join(contact)
        also_by = m.get("also_by", [])
        also_by_tex = ""
        if also_by:
            items = "\\\\[3pt]\n".join(r"\emph{" + tex_text(x) + "}" for x in also_by)
            also_by_tex = (
                "\\cleardoublepage\\thispagestyle{empty}\n\\null\\vskip 1.6in\n"
                "\\begin{center}\\spacedcaps{also by "
                + tex_text(m["author"]).lower()
                + "}\\par\\vskip 18pt\n"
                + items
                + "\n\\end{center}\n"
            )
        numbered = m.get("number_chapters", True)
        body = []
        for chapter in book.front:
            body.append(self._chapters.render(chapter, numbered))
        for part_title, chapters in book.parts:
            body.append(f"\\part{{{tex_text(part_title)}}}\n")
            for chapter in chapters:
                body.append(self._chapters.render(chapter, numbered))
        if book.back:
            body.append("\\backmatter\n\\pagestyle{fine}\n")
        for chapter in book.back:
            body.append(self._chapters.render(chapter, numbered))
        about = self._tex.paragraphs(m["author_bio"])
        dedication = tex_text(m.get("dedication", "").strip())
        notes = self._tex.paragraphs(m.get("copyright_notes", ""))
        document_class = "fine-book-hardcover" if hardcover else "fine-book"

        return rf"""% Generated by engineering-influence from {book.slug}.toml. Do not edit.
\documentclass{{{document_class}}}
\setpdfinfo{{{m["title"]}: {m.get("subtitle", "")}}}{{{m["author"]}}}{{{m.get("edition", "")}}}
\setbooktitlehead{{{title}}}
\begin{{document}}
\frontmatter
\pagestyle{{empty}}
% Half title
\null\vskip 2.3in
\begin{{center}}{{\displayfont\fontsize{{22}}{{28}}\selectfont {title}\par}}\vskip 16pt\ornament\end{{center}}
{also_by_tex}
% Title page
\cleardoublepage\thispagestyle{{empty}}
\null\vskip 1.25in
\begin{{center}}
{{\displayfont\fontsize{{34}}{{40}}\selectfont {title}\par}}
\vskip 18pt
\begin{{minipage}}{{0.82\textwidth}}\centering\displayfont\itshape\fontsize{{14.5}}{{19}}\selectfont {subtitle}\end{{minipage}}\par
\vskip 30pt\ornament[2.4em]\vskip 30pt
\spacedcaps{{{author.lower()}}}\par
\vfill
{{\small\spacedcaps{{{publisher.lower()}}}}}\par
\end{{center}}
% Copyright page
\clearpage\thispagestyle{{empty}}
\null\vfill
{{\fontsize{{9}}{{12.5}}\selectfont\raggedright\setlength{{\parindent}}{{0pt}}\setlength{{\parskip}}{{6pt}}
\emph{{{title}: {subtitle}}}\par
{tex_text(m["edition"])}\par
Copyright \copyright\ {year} {publisher}. All rights reserved.\par
{isbn_line}Published by {publisher}\\
{contact_tex}\par
{notes}\par
}}
% Dedication
\cleardoublepage\thispagestyle{{empty}}
\null\vskip 2.2in
\begin{{center}}\begin{{minipage}}{{0.72\textwidth}}\centering\itshape\fontsize{{12}}{{17}}\selectfont {dedication}\end{{minipage}}\end{{center}}
% Contents
\cleardoublepage
\pagestyle{{fine}}
\setbooktitlehead{{{title}}}
\tableofcontents*
\clearpage
\mainmatter
{"".join(body)}
% About the author
\chapter*{{About the Author}}
\addcontentsline{{toc}}{{chapter}}{{About the Author}}
\chapterheadmark{{About the Author}}
{about}
\end{{document}}
"""
