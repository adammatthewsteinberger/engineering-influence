"""The ebook LaTeX document, converted to EPUB 3 by tex4ebook."""

from engineering_influence.publishing.typesetting.book import Book
from engineering_influence.publishing.typesetting.chapter_tex import ChapterTex
from engineering_influence.publishing.typesetting.tex_text import TexText


class EbookDocument:
    """The same chapters as the print interior, set with the fine-ebook class.

    The ebook and the print interior share one Markdown to LaTeX conversion.
    """

    def __init__(self) -> None:
        self._tex = TexText()
        self._chapters = ChapterTex()

    def render(self, book: Book) -> str:
        """Return the complete .tex source."""
        m = book.meta
        tex_text = self._tex.text
        title = tex_text(m["title"])
        subtitle = tex_text(m.get("subtitle", ""))
        author = tex_text(m["author"])
        publisher = tex_text(m["publisher"])
        year = m.get("year", 2026)
        # A print ISBN identifies the paperback; the ebook shows only its own.
        isbn_line = (
            f"ISBN {tex_text(m['ebook_isbn'])} (ebook)\\par\n" if m.get("ebook_isbn") else ""
        )
        contact = [f"Published by {publisher}"]
        if m.get("website"):
            contact.append(r"\url{" + m["website"] + "}")
        if m.get("email"):
            contact.append(r"\href{mailto:" + m["email"] + "}{" + tex_text(m["email"]) + "}")
        contact_tex = "\\\\\n".join(contact)
        notes = self._tex.paragraphs(m.get("copyright_notes", ""))
        dedication = tex_text(m.get("dedication", "").strip())
        dedication_tex = (
            f"\\begin{{ebookdedication}}\n{dedication}\n\\end{{ebookdedication}}\n"
            if dedication
            else ""
        )
        subtitle_tex = f"\\textit{{{subtitle}}}\\par\n" if subtitle else ""
        numbered = m.get("number_chapters", True)
        body = []
        for chapter in book.front:
            body.append(self._chapters.render(chapter, numbered))
        for part_title, chapters in book.parts:
            body.append(f"\\part{{{tex_text(part_title)}}}\n")
            for chapter in chapters:
                body.append(self._chapters.render(chapter, numbered))
        for chapter in book.back:
            body.append(self._chapters.render(chapter, numbered))
        about = self._tex.paragraphs(m["author_bio"])
        also_by = m.get("also_by", [])
        if also_by:
            about += (
                "\n\n\\section*{Also by "
                + author
                + "}\n"
                + "\n\n".join(r"\emph{" + tex_text(x) + "}" for x in also_by)
            )
        edition_line = f"{title}: {subtitle}" if subtitle else title

        return rf"""% Generated by engineering-influence from {book.slug}.toml. Do not edit.
\documentclass[11pt,oneside,openany]{{book}}
\usepackage{{fine-ebook}}
\title{{{title}}}
\author{{{author}}}
\date{{{year}}}
\setbookmeta{{{title}}}{{{subtitle}}}{{{author}}}{{{publisher}}}
\begin{{document}}
\begin{{ebooktitlepage}}
{{\Large {title}\par}}
{subtitle_tex}\ornament\par
\textsc{{{author}}}\par
\textsc{{{publisher}}}\par
\end{{ebooktitlepage}}
\begin{{ebookcopyright}}
\emph{{{edition_line}}}\par
{tex_text(m["edition"])}\par
Copyright \copyright\ {year} {publisher}. All rights reserved.\par
{isbn_line}{contact_tex}\par
{notes}\par
\end{{ebookcopyright}}
{dedication_tex}\tableofcontents
{"".join(body)}
\chapter*{{About the Author}}
\addcontentsline{{toc}}{{chapter}}{{About the Author}}
{about}
\end{{document}}
"""
